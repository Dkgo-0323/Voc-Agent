"""Replay real questions through login, /api/ask SSE and persisted receipts.

Run from the repository root. Uses configured PostgreSQL, Milvus and model APIs.
Only chat sessions/messages are created; source reviews are never modified.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import os
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from time import monotonic, sleep
from uuid import UUID, uuid4

# Support `python scripts/run_conversation_e2e.py` without installing the repo.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import httpx  # noqa: E402

from shared.eval.business_questions import HOLDOUT, SCENARIOS  # noqa: E402
from shared.eval.conversation_e2e import assess, parse_sse, repair_hint  # noqa: E402


async def inspect_turn(done: dict) -> dict:
    from sqlalchemy import select

    from backend.app.core.database import get_db_context
    from backend.app.db.models import ChatMessage

    async with get_db_context() as db:
        assistant = await db.get(ChatMessage, UUID(done["assistant_message_id"]))
        user = await db.get(ChatMessage, UUID(done["user_message_id"]))
        if assistant is None or user is None or user.session_id != assistant.session_id:
            raise ValueError("Missing persisted turn")
        row = {
            k: getattr(assistant, k)
            for k in ("content", "tool_calls", "tool_results", "cited_ids")
        }
        row.update(
            id=str(assistant.id),
            session_id=str(assistant.session_id),
            prompt=user.content,
        )
        # Check every claimed citation exists in real storage with matching scope.
        from backend.app.db.models import AspectMention

        ids = (assistant.cited_ids or {}).get("mention_ids", [])
        mentions = (
            (
                await db.execute(
                    select(AspectMention).where(
                        AspectMention.id.in_([UUID(i) for i in ids])
                    )
                )
            )
            .scalars()
            .all()
            if ids
            else []
        )
        row["verified_citations"] = {
            str(m.id): {"sku_code": m.sku_code, "document_id": str(m.document_id)}
            for m in mentions
        }
        return row


async def count_oracle(sku: str) -> int:
    # Independent aggregate, never a reference answer generated by the model.
    from sqlalchemy import func, select

    from backend.app.core.database import get_db_context
    from backend.app.core.settings import settings
    from backend.app.db.models import AspectMention, Sku

    async with get_db_context() as db:
        return int(
            (
                await db.execute(
                    select(func.count(func.distinct(AspectMention.document_id)))
                    .join(Sku, Sku.sku_code == AspectMention.sku_code)
                    .where(
                        Sku.dashboard_enabled.is_(True),
                        Sku.sku_code == sku,
                        AspectMention.quality_score
                        >= settings.aspect_quality_threshold,
                    )
                )
            ).scalar_one()
        )


async def create_test_session(title: str) -> str:
    from backend.app.core.database import get_db_context
    from backend.app.db.repositories.conversation_repo import ConversationRepository

    async with get_db_context() as db:
        session = await ConversationRepository(db).create_session(
            title=title, created_by="admin"
        )
        return str(session.id)


async def failed_turn_receipt(session_id: str, prompt: str) -> dict | None:
    """An SSE error has no done IDs; recover only this isolated test session."""
    from backend.app.core.database import get_db_context
    from backend.app.db.repositories.conversation_repo import ConversationRepository

    async with get_db_context() as db:
        rows = await ConversationRepository(db).get_recent_messages(
            UUID(session_id), limit=2
        )
    if (
        len(rows) != 2
        or rows[0].role != "user"
        or rows[0].content != prompt
        or rows[1].role != "assistant"
    ):
        return None
    return await inspect_turn(
        {"user_message_id": str(rows[0].id), "assistant_message_id": str(rows[1].id)}
    )


def save_report(path: Path, report: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{uuid4().hex}.tmp")
    temp.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    # Antivirus/indexers can briefly hold a Windows read handle without delete
    # sharing. Keep the previous complete JSON until replacement succeeds.
    for attempt in range(5):
        try:
            temp.replace(path)
            return
        except PermissionError:
            if attempt == 4:
                raise
            sleep(0.1)


async def run(args) -> int:
    suite = HOLDOUT if args.suite == "holdout" else SCENARIOS
    selected = [s for s in suite if not args.case or s.id in args.case]
    if not selected or (args.case and set(args.case) - {s.id for s in suite}):
        raise ValueError("Unknown/empty scenario selection")
    turns = sum(len(s.turns) for s in selected) * args.repeat
    report = {
        "schema_version": 1,
        "started_at": datetime.now(UTC).isoformat(),
        "suite": args.suite,
        "mode": "real-model-real-storage-api",
        "planned_turns": turns,
        "results": [],
        "complete": False,
        "semantic_review": "pending",
        "scope": "FastAPI login + SSE + real models/storage + persisted receipts; browser rendering excluded",
    }
    save_report(args.output, report)
    # Import runtime only after CLI validation, so --help never loads credentials.
    from backend.app.core.settings import settings

    settings.llm_max_retries = 0
    settings.log_level = "WARNING"
    settings.app_env = "production"  # Disable SQL echo of prompts and answers.
    from backend.app.main import create_app

    logging.getLogger("sqlalchemy.engine").setLevel(logging.WARNING)
    app = create_app()
    report["configuration"] = {
        "chat_model": settings.llm_model,
        "embedding_model": settings.embedding_model,
        "quality_threshold": settings.aspect_quality_threshold,
        "sdk_retries": 0,
        "upper_bound_chat_attempts": turns * 8,
        "upper_bound_rag_calls": turns * 3,
        "max_output_tokens_per_chat": settings.llm_max_tokens,
    }
    try:
        async with (
            app.router.lifespan_context(app),
            httpx.AsyncClient(
                transport=httpx.ASGITransport(app=app),
                base_url="http://e2e.local",
                timeout=180,
            ) as client,
        ):
            login = await client.post(
                "/api/auth/login",
                json={
                    "password": os.environ.get("VOC_E2E_PASSWORD")
                    or settings.admin_password
                },
            )
            login.raise_for_status()
            client.headers["Authorization"] = "Bearer " + login.json()["access_token"]
            for repeat in range(args.repeat):
                for scenario in selected:
                    session_id = await create_test_session(
                        f"[E2E] {scenario.id} #{repeat + 1}"
                    )
                    for question in scenario.turns:
                        done = None
                        started = monotonic()
                        row = {
                            "scenario": scenario.id,
                            "question_id": question.id,
                            "repeat": repeat + 1,
                            "prompt": question.prompt,
                            "rubric": question.rubric,
                            "failures": [],
                        }
                        try:
                            oracle = (
                                await count_oracle(question.sku)
                                if question.count and question.sku
                                else None
                            )
                            async with asyncio.timeout(args.turn_timeout):
                                response = await client.post(
                                    "/api/ask",
                                    json={
                                        "session_id": session_id,
                                        "message": question.prompt,
                                    },
                                )
                            response.raise_for_status()
                            events = parse_sse(response.text)
                            done = next(
                                (e for e in events if e["event_type"] == "done"), None
                            )
                            persisted = (
                                await inspect_turn(done)
                                if done
                                else await failed_turn_receipt(
                                    session_id, question.prompt
                                )
                            )
                            row.update(
                                events=events,
                                persisted=persisted,
                                expected_count=oracle,
                            )
                            row["failures"] = assess(
                                question,
                                events,
                                persisted=persisted,
                                expected_count=oracle,
                            )
                            if done:
                                if session_id and done["session_id"] != session_id:
                                    row["failures"].append("followup_session_changed")
                                session_id = done["session_id"]
                            if persisted:
                                verified = persisted["verified_citations"]
                                for e in events:
                                    if e["event_type"] == "citation":
                                        c = e["citation"]
                                        if verified.get(c["mention_id"]) != {
                                            "sku_code": c["sku_code"],
                                            "document_id": c["document_id"],
                                        }:
                                            row["failures"].append(
                                                "citation_not_in_database"
                                            )
                        except Exception as exc:
                            # Exceptions can include provider credentials/URLs: retain type only.
                            row["failures"].append(
                                "execution_exception:" + type(exc).__name__
                            )
                        row["elapsed_seconds"] = round(monotonic() - started, 2)
                        row["repair_hints"] = list(
                            dict.fromkeys(repair_hint(f) for f in row["failures"])
                        )
                        row["automatic_pass"] = not row["failures"]
                        report["results"].append(row)
                        save_report(args.output, report)
                        print(
                            f"{scenario.id}/{question.id}: {'PASS' if row['automatic_pass'] else 'FAIL'} {row['failures']}",
                            flush=True,
                        )
                        if not row["automatic_pass"] and (
                            not args.keep_going or done is None
                        ):
                            # Never run a follow-up as a fresh session after losing its parent.
                            if args.keep_going:
                                break
                            report["complete"] = len(report["results"]) == turns
                            report["automatic_pass"] = False
                            return 1
        report["complete"] = len(report["results"]) == turns
        report["automatic_pass"] = report["complete"] and all(
            r["automatic_pass"] for r in report["results"]
        )
        return 0 if report["automatic_pass"] else 1
    except Exception as exc:
        report["infrastructure_error"] = type(exc).__name__
        return 2
    finally:
        report["summary"] = {
            "executed_turns": len(report["results"]),
            "passed_turns": sum(r["automatic_pass"] for r in report["results"]),
            "failed_turns": sum(not r["automatic_pass"] for r in report["results"]),
            "failure_counts": dict(
                Counter(f for r in report["results"] for f in r["failures"])
            ),
        }
        save_report(args.output, report)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--suite", choices=("development", "holdout"), default="development"
    )
    parser.add_argument(
        "--case", action="append", help="Scenario ID; repeat to select several"
    )
    parser.add_argument("--repeat", type=int, choices=range(1, 6), default=1)
    parser.add_argument("--turn-timeout", type=float, default=180)
    parser.add_argument(
        "--keep-going",
        action="store_true",
        help="Continue independent scenarios after a failed answer",
    )
    parser.add_argument(
        "--output", type=Path, default=Path("artifacts/e2e/conversation-report.json")
    )
    args = parser.parse_args()
    if not 0 < args.turn_timeout <= 600:
        parser.error("turn-timeout must be in (0, 600]")
    raise SystemExit(asyncio.run(run(args)))


if __name__ == "__main__":
    main()
